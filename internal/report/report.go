// WebAuditReport es la foto exportable de una auditoría web.
type WebAuditReport struct {
	Target      string          `json:"target"`
	GeneratedAt time.Time       `json:"generated_at"`
	Score       int             `json:"score"`
	Grade       string          `json:"grade"`
	Summary     map[string]int  `json:"summary"`
	Findings    []audit.Finding `json:"findings"`
}

// New construye el reporte y calcula puntaje + calificación.
func New(target string, findings []audit.Finding) WebAuditReport {
	counts := map[string]int{"CRITICAL": 0, "HIGH": 0, "MEDIUM": 0, "LOW": 0}
	score := 100

	for _, f := range findings {
		counts[f.Severity]++
		switch f.Severity {
		case "CRITICAL":
			score -= 50
		case "HIGH":
			score -= 20
		case "MEDIUM":
			score -= 5
		case "LOW":
			score -= 1
		}
	}

	if score < 0 {
		score = 0
	}

	grade := calculateGrade(score)

	return WebAuditReport{
		Target:      target,
		GeneratedAt: time.Now(),
		Score:       score,
		Grade:       grade,
		Summary:     counts,
		Findings:    findings,
	}
}

func calculateGrade(score int) string {
	switch {
	case score >= 90:
		return "A"
	case score >= 70:
		return "B"
	case score >= 50:
		return "C"
	case score >= 30:
		return "D"
	default:
		return "F"
	}
}

// SaveJSON escribe el reporte en JSON indentado.
func SaveJSON(r WebAuditReport, path string) error {
	data, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, data, 0644)
}

