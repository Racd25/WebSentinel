// SaveHTML renderiza el reporte con html/template.
func SaveHTML(r WebAuditReport, path string) error {
	t, err := template.New("report").Parse(htmlTmpl)
	if err != nil {
		return err
	}
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return t.Execute(f, r)
}
